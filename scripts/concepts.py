"""Concept library for the text->regex SFT task.

Each concept defines a POOL of test strings plus a HELD set. Variants are
generated by sampling which pool strings become VISIBLE (shown in the prompt);
everything else -- the rest of the pool plus the entire held set -- becomes
HIDDEN (grading only).

The held set is what makes the overfitting signal work. It contains the strings
that exercise the part of the instruction no visible example demonstrates, so a
model that pattern-matches the shown examples instead of reading the
instruction fails them. Held strings must NEVER be sampled into visible.

`traps` names the specific mistakes the held set is built to catch; difficulty
is derived from trap count so the mix can be stratified without hand-labelling.
"""

